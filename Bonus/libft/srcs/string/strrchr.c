#include "string.h"

char	*str_rchr(const char *s, int c)
{
	int	i;

	i = str_len(s);
	while (i >= 0)
	{
		if (s[i] == (char)c)
			return ((char *)s + i);
		i--;
	}
	return (NULL);
}
